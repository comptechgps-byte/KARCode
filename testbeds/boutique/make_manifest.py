#!/usr/bin/env python3
"""
Derive testbeds/boutique/boutique.yaml from the unmodified upstream Online
Boutique v0.10.7 release manifest. Changes are minimal and deliberate:
  * all objects in namespace `boutique`;
  * `frontend-external` becomes a NodePort (30080) so the harness can probe
    the storefront from the Kind network (no cloud LoadBalancer);
  * the load generator runs 3 simulated users (background traffic only).
Deployment strategy (RollingUpdate), replica counts, probes and resource
limits are left exactly as upstream: the point of this testbed is realistic
defaults.
"""
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
docs = [d for d in yaml.safe_load_all((HERE / "upstream-kubernetes-manifests.yaml").read_text()) if d]
for d in docs:
    d.setdefault("metadata", {})["namespace"] = "boutique"
    if d["kind"] == "Service" and d["metadata"]["name"] == "frontend-external":
        d["spec"]["type"] = "NodePort"
        for p in d["spec"]["ports"]:
            p["nodePort"] = 30080
    if d["kind"] == "Deployment" and d["metadata"]["name"] == "loadgenerator":
        for c in d["spec"]["template"]["spec"]["containers"]:
            for e in c.get("env", []):
                if e["name"] == "USERS":
                    e["value"] = "3"
header = "# GENERATED by make_manifest.py from upstream v0.10.7 — do not edit by hand.\n"
(HERE / "boutique.yaml").write_text(header + yaml.safe_dump_all(docs, sort_keys=False))
print(f"wrote {len(docs)} objects to {HERE / 'boutique.yaml'}")
