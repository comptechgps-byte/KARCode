#!/usr/bin/env python3
"""
paper_numbers_v7.py — label sensitivity of the rollback-trap study.
The rollback share does not depend on which action is labelled correct; the
"correct" share does. We re-score the scored traps under a lenient rule (any
non-destructive action other than rollback counts as acceptable, except that
oom-growth still requires patch-limits) and report the range per model.
Writes paper/results_macros_v7.tex.

    python benchmark/paper_numbers_v7.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paper_numbers import macro_name, pct  # noqa: E402
from paper_numbers_v4 import FAMILY  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
R, P = ROOT / "results", ROOT / "paper"
SCORED = ["transient-old-release", "oom-old-release", "dependency-down", "external-config-change",
          "node-lost", "cert-expired"]
DESTRUCTIVE = {"drain-node", "cordon-node", "delete-pvc"}
LENIENT_OK = {"noop", "restart-pod", "scale-deployment", "patch-limits", "revert-network-policy"}


def lenient(row) -> bool:
    if row.fault == "oom-old-release":
        return row.action == "patch-limits"
    return row.action in LENIENT_OK and row.action not in DESTRUCTIVE


def main():
    frames = []
    for sub in ("prompt_traps", "prompt_traps2"):
        for f in sorted((R / sub).glob("*.csv")):
            if f.stem in FAMILY:
                d = pd.read_csv(f)
                d["model"] = f.stem
                frames.append(d)
    d = pd.concat(frames)
    d = d[d.fault.isin(SCORED)].copy()
    d["strict"] = d.correct.astype(str).str.lower().eq("true")
    d["lenient"] = d.apply(lenient, axis=1)
    m: dict[str, str] = {}
    for mm, g in d.groupby("model"):
        m[macro_name("TrapLenient", mm)] = pct(g.lenient.mean())
    by = d.groupby("model")
    m["TrapLenientMin"] = pct(by.lenient.mean().min())
    m["TrapLenientMax"] = pct(by.lenient.mean().max())
    m["TrapStrictMax"] = pct(by.strict.mean().max())
    # under the lenient rule, every non-rollback answer counts, so lenient = 1 - rollback - destructive
    m["TrapDestructiveCalls"] = str(int(d.action.isin(DESTRUCTIVE).sum()))
    out = P / "results_macros_v7.tex"
    lines = ["% generated by benchmark/paper_numbers_v7.py — do not edit by hand"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items()) if re.fullmatch(r"[A-Za-z]+", k)]
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
